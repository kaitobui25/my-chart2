let locale: Locale = localStorage.getItem(LOCALE_KEY) === 'vi' ? 'vi' : 'en';

export function getLocale(): Locale {
  return locale;
}

export function localeTag(): string {
  return locale === 'vi' ? 'vi-VN' : 'en-US';
}

export function tr(source: string): string {
  return locale === 'en' ? (ENGLISH[source] ?? source) : source;
}

export function setLocale(next: Locale): void {
  if (next === locale) return;
  localStorage.setItem(LOCALE_KEY, next);
  window.location.reload();
}

function translateTextNode(node: Text): void {
  const value = node.nodeValue ?? '';
  const trimmed = value.trim();
  if (!trimmed) return;
  const translated = tr(trimmed);
  if (translated === trimmed) return;
  node.nodeValue = value.replace(trimmed, translated);
}

function translateAttributes(element: Element): void {
  for (const name of ['title', 'aria-label', 'placeholder', 'data-label']) {
    const value = element.getAttribute(name);
    if (!value) continue;
    const translated = tr(value);
    if (translated !== value) element.setAttribute(name, translated);
  }
}

export function translateDom(root: ParentNode = document): void {
  document.documentElement.lang = locale;
  if (locale !== 'en') return;
  if (root instanceof Element) translateAttributes(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
    else translateAttributes(node as Element);
    node = walker.nextNode();
  }
}

export function observeTranslations(): () => void {
  if (locale !== 'en') return () => undefined;
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') translateTextNode(record.target as Text);
      if (record.type === 'attributes') translateAttributes(record.target as Element);
      for (const node of record.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
        else if (node instanceof Element) translateDom(node);
      }
    }
  });
  observer.observe(document.documentElement, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['title', 'aria-label', 'placeholder', 'data-label'],
  });
  return () => observer.disconnect();
}
